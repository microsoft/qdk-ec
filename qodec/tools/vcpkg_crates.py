"""Write the crates.io closure of qodec-c as a vcpkg port include file.

The vcpkg port builds offline from a vendored crate directory. This lists every
registry package that qodec-c needs to build (normal and build dependencies, all
platforms) with the SHA-512 of its `.crate` archive, which `vcpkg_download_distfile`
requires. Run it with the release's resolved Cargo.lock in the workspace root:

    python qodec/tools/vcpkg_crates.py > <vcpkg>/ports/qodec/crates.cmake
"""

from collections.abc import Iterable
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import urllib.request


ROOT = Path(__file__).resolve().parents[2]
PACKAGE = "qodec-c"
CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index"


def build_closure(metadata: dict, root_name: str) -> list[dict]:
    """Return sorted registry packages reachable without dev-only edges."""
    packages = {package["id"]: package for package in metadata["packages"]}
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    root = next(
        (package for package in packages.values()
         if package["name"] == root_name and package["source"] is None),
        None,
    )
    if root is None:
        raise ValueError(f"Cargo metadata has no workspace package named {root_name!r}")

    pending = [root["id"]]
    reached = set(pending)
    while pending:
        package_id = pending.pop()
        for dependency in nodes[package_id]["deps"]:
            dependency_id = dependency["pkg"]
            is_non_dev_dependency = any(kind["kind"] != "dev" for kind in dependency["dep_kinds"])
            if is_non_dev_dependency and dependency_id not in reached:
                reached.add(dependency_id)
                pending.append(dependency_id)

    unexpected = sorted(
        packages[package_id]["name"]
        for package_id in reached
        if packages[package_id]["source"] not in (None, CRATES_IO)
    )
    if unexpected:
        raise ValueError(f"only crates.io and path dependencies can be vendored: {unexpected}")
    closure = [
        packages[package_id]
        for package_id in reached
        if packages[package_id]["source"] == CRATES_IO
    ]
    return sorted(closure, key=lambda package: (package["name"], package["version"]))


def crate_sha512(name: str, version: str) -> str:
    url = f"https://static.crates.io/crates/{name}/{name}-{version}.crate"
    with urllib.request.urlopen(url) as response:
        return hashlib.sha512(response.read()).hexdigest()


def cmake_list(crates: Iterable[tuple[str, str, str]]) -> str:
    lines = [f"    {name} {version} {sha512}" for name, version, sha512 in crates]
    header = "# Generated by qodec/tools/vcpkg_crates.py: name version SHA-512 of the .crate archive.\n"
    return header + "set(QODEC_CRATES\n" + "\n".join(lines) + "\n)\n"


def main() -> int:
    command = [
        "cargo", "metadata", "--format-version", "1", "--locked",
        "--manifest-path", str(ROOT / "Cargo.toml"),
    ]
    metadata = json.loads(subprocess.run(command, check=True, capture_output=True, text=True).stdout)
    closure = build_closure(metadata, PACKAGE)
    sys.stdout.write(cmake_list((p["name"], p["version"], crate_sha512(p["name"], p["version"])) for p in closure))
    return 0


if __name__ == "__main__":
    sys.exit(main())
